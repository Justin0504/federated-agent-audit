"""Refresh upload fields from the compiled preprint, without submitting anything."""
from pathlib import Path
import hashlib
import json
import re
import subprocess

root = Path(__file__).resolve().parent
source = (root / 'main.tex').read_text()
abstract = source.split('% ARXIV_ABSTRACT_BEGIN', 1)[1].split('% ARXIV_ABSTRACT_END', 1)[0]
abstract = abstract.replace(r'\ext{}', 'a2a.privacy/v1').replace(r'\%', '%')
abstract = re.sub(r'\s+', ' ', abstract).strip()
if '\\' in abstract:
    raise ValueError('Unconverted LaTeX in abstract; update explicit conversion')
info = subprocess.check_output(['pdfinfo', str(root / 'main.pdf')], text=True)
pages = int(re.search(r'Pages:\s+(\d+)', info).group(1))
aux = (root / 'main.aux').read_text()
main_end = int(re.search(r'\\newlabel\{sec:main-end\}\{\{[^}]*\}\{(\d+)\}', aux).group(1))
text = f'''# arXiv upload candidate

## Title
Agents Over-Share: Center-Blind Auditing for Multi-Tenant Agent Privacy

## Author
Aojie (Justin) Yuan — University of Southern California

## Suggested categories
Primary: cs.CR (Cryptography and Security). Suggested cross-list: cs.MA (Multiagent Systems), subject to arXiv moderation.

## Comments
{pages} pages, including references and appendices. The main narrative ends
on page {main_end} (including the cover); historical experiments and development
diagnostics are in the appendices. Research code and evaluation
artifacts: https://github.com/Justin0504/federated-agent-audit

## Abstract
{abstract}

## Source package and verification
Upload `arxiv_submission.zip`, generated by `make arxiv`. It contains real copies
of the required figure resources, `methodology.tex`, `agentdojo_external.tex`, `historical_measurements.tex`, bibliography source and
`main.bbl`. The staging directory is compiled separately with Tectonic before
packaging; this checks local dependency completeness. It does not certify arXiv's
server-side TeX environment. Inspect the preview produced by arXiv before final
submission. The PDF and source archive are local candidates, not an uploaded paper.

Choose a license in the submission form after confirming your author/institution
preferences. This file makes no assurance about any venue's current preprint policy.

## Evidence limits retained in this version
- The new 20-task set was authored after gate freezing, but is not externally
  authored or human-adjudicated. Slot completion and literal privacy-marker
  matching do not establish general semantic utility or confidentiality.
- External AgentDojo results use 1,132 archived action-prefix replays and native
  predicates; they are not new live model runs. Stopping on first block exposes
  utility loss. Historical-label mismatches and checker exceptions are reported.
- The separate live formal comparison contains 256 episodes on 32 task IDs and
  eight methods, one 14B model and one seed. Native attack successes are sparse;
  zero of 16 does not establish privacy superiority.
- All five release-gate arms reuse the same generated proposal. Partial arms are
  ablations, not reproductions of other papers' systems.
- Historical model names are experiment aliases; missing provider-version
  provenance prevents precise model-ranking claims. New Jetstream runs pin a
  checkpoint revision and retain source hashes.
- Database mailbox commit is the tested release point. External delivery,
  bypass channels, arbitrary paraphrases and correctness of trusted source facts
  are outside this release gate's evaluated guarantee.
- Publishing the preprint is separate from publishing all newly generated local
  artifacts to the linked repository; verify that artifact availability matches
  the paper before completing submission.
'''
(root / 'ARXIV.md').write_text(text)
paths = ['core_narrative.tex', 'appendix_audit_details.tex', 'appendix_release_details.tex', 'appendix_development.tex', 'appendix_detector_studies.tex', 'core_case_figure.tex', 'core_outcome_figure.tex', 'appendix_cost_figure.tex', 'main.tex', 'paired_protocol.tex', 'final_native_results.tex', 'final_native_appendix.tex', 'methodology.tex', 'agentdojo_external.tex', 'historical_measurements.tex', 'references.bib', 'main.pdf', 'arxiv_submission.zip', 'ARXIV.md']
manifest = {name: hashlib.sha256((root / name).read_bytes()).hexdigest()
            for name in paths if (root / name).exists()}
(root / 'release_manifest.json').write_text(json.dumps({'pages': pages, 'sha256': manifest}, indent=2)+'\n')
print(f'Refreshed metadata: {pages} pages; {len(abstract.split())} abstract words')
